const { plural } = require('./_util');

const AR_MONTHS = ['يناير', 'فبراير', 'مارس', 'أبريل', 'مايو', 'يونيو', 'يوليو', 'أغسطس', 'سبتمبر', 'أكتوبر', 'نوفمبر', 'ديسمبر'];
// a period captured from stored English text (2026-09, 2026-Q3, 2026) written the Arabic way
const arPeriod = (p) => {
  const s = String(p);
  let m = /^(\d{4})-(\d{2})$/.exec(s);
  if (m) return `${AR_MONTHS[Number(m[2]) - 1]} ${m[1]}`;
  m = /^(\d{4})-Q([1-4])$/.exec(s);
  if (m) return `الربع ${m[2]} من ${m[1]}`;
  return s;
};
const months = (n) => plural(n, 'شهر واحد', 'شهران', '{n} أشهر', '{n} شهرًا');

